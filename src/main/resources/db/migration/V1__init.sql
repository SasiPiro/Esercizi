-- Initial schema (PostgreSQL). Instants are TIMESTAMP WITH TIME ZONE, local date-times TIMESTAMP.
-- Applied by Flyway; never edit a released migration, add a new V<n>__ file instead.
-- =============================================
-- CORE ENTITIES
-- =============================================

CREATE TABLE user_app (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    vip BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,

    -- Composite primary key prevents duplicates (same role for same user)
    PRIMARY KEY (user_id, role_id),

    -- Constraint referencing the user table
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id)
        REFERENCES user_app(id)
        ON DELETE CASCADE,

    -- Constraint referencing the role table
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES roles(id)
        ON DELETE CASCADE
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    base_price DECIMAL(19, 2) NOT NULL
);

-- =============================================
-- CART SYSTEM
-- =============================================

CREATE TABLE cart (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_status VARCHAR(20)
);

CREATE TABLE cart_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT,
    product_id BIGINT,
    quantity INTEGER NOT NULL,

    CONSTRAINT fk_cart_item_cart FOREIGN KEY (cart_id) REFERENCES cart(id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_item_product FOREIGN KEY (product_id) REFERENCES product(id),
    CHECK (quantity >= 1)
);

CREATE TABLE cart_ownership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL UNIQUE,
    user_id BIGINT UNIQUE,                 -- at most one open cart per user
    anonymous_id VARCHAR(64) UNIQUE,       -- at most one open cart per guest
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ownership_cart FOREIGN KEY (cart_id) REFERENCES cart(id) ON DELETE CASCADE,
    CONSTRAINT fk_ownership_user FOREIGN KEY (user_id) REFERENCES user_app(id),
    -- exactly one owner: either a registered user or a guest
    CONSTRAINT chk_ownership_single_owner CHECK ((user_id IS NULL) <> (anonymous_id IS NULL))
);

-- =============================================
-- ORDERS
-- Prices and product codes are a snapshot taken at checkout: no foreign key to product,
-- so catalog changes never alter a past order
-- =============================================

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(64) NOT NULL UNIQUE,   -- a retried checkout cannot create a second order
    user_id BIGINT,
    anonymous_id VARCHAR(64),
    initial_price DECIMAL(19, 2) NOT NULL,
    final_price DECIMAL(19, 2) NOT NULL,
    coupon_code VARCHAR(50),
    applied_strategies VARCHAR(255) NOT NULL,
    placed_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES user_app(id),
    -- exactly one owner: either a registered user or a guest
    CONSTRAINT chk_orders_single_owner CHECK ((user_id IS NULL) <> (anonymous_id IS NULL))
);

CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_anonymous ON orders (anonymous_id);

CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_code VARCHAR(255) NOT NULL,
    unit_price DECIMAL(19, 2) NOT NULL,
    quantity INTEGER NOT NULL,

    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
    CHECK (quantity >= 1)
);

-- =============================================
-- COUPON SYSTEM (with Optimistic Locking)
-- =============================================

CREATE TABLE coupon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    discount_percentage DECIMAL(5, 4) NOT NULL,
    usage_limit INTEGER NOT NULL,
    current_usage INTEGER NOT NULL DEFAULT 0,
    expiry_date TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 0,

    CHECK (discount_percentage > 0 AND discount_percentage <= 1),
    CHECK (current_usage >= 0)
);

-- =============================================
-- SCHEDULER LOCKS (ShedLock)
-- One row per job: with several replicas only the instance holding the lock runs it
-- =============================================

CREATE TABLE shedlock (
    name VARCHAR(64) NOT NULL,
    lock_until TIMESTAMP NOT NULL,
    locked_at TIMESTAMP NOT NULL,
    locked_by VARCHAR(255) NOT NULL,
    PRIMARY KEY (name)
);

-- =============================================
-- EVENT PUBLICATION REGISTRY (Spring Modulith)
-- One row per event and listener, written in the publishing transaction and completed
-- when the listener succeeds: incomplete rows are events still to be (re)delivered
-- =============================================

CREATE TABLE event_publication (
    id UUID NOT NULL PRIMARY KEY,
    listener_id VARCHAR(512) NOT NULL,
    event_type VARCHAR(512) NOT NULL,
    serialized_event VARCHAR(4000) NOT NULL,
    publication_date TIMESTAMP WITH TIME ZONE NOT NULL,
    completion_date TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20),
    completion_attempts INTEGER NOT NULL DEFAULT 0,
    last_resubmission_date TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_event_publication_completion_date ON event_publication (completion_date);
